import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
let sharp;
for(const name of ['sharp',path.resolve(path.dirname(process.execPath),'../node_modules/sharp')]){try{sharp=require(name);break}catch{}}
if(!sharp)throw new Error('需要 sharp；请使用附带 sharp 的 Node 运行。');
const root=fileURLToPath(new URL('../../',import.meta.url));
const definitions=JSON.parse(fs.readFileSync(path.join(root,'dev/media/replacements.json'),'utf8'));
const remote=JSON.parse(fs.readFileSync(path.join(root,'dev/media/remote-sources.json'),'utf8'));
const generated=JSON.parse(fs.readFileSync(path.join(root,'dev/media/generated-sources.json'),'utf8').replace(/^\uFEFF/,''));
const output=path.join(root,'assets/product-media');fs.mkdirSync(output,{recursive:true});
const sources=new Map(),catalog={},files=[],report=[];
for(const name of fs.readdirSync(path.join(root,'assets/reference-images'))){
 const relative='assets/reference-images/'+name;
 sources.set(relative,{source:relative});
}
for(const item of definitions.replacements)sources.set(item.target,item);
const encoded=new Map();
for(const [target,item] of sources){
 const absolute=path.join(root,item.source),bytes=fs.readFileSync(absolute);
 const identity=crypto.createHash('sha256').update(bytes).update(JSON.stringify({crop:item.crop||null,recipe:'webp-v1-thumb112-224-q82-full960-q86-trim12'})).digest('hex').slice(0,16);
 if(!encoded.has(identity)){
  const metadata=await sharp(bytes).metadata();
  // Thumbnails are square with the complete subject; high-resolution originals never enter the initial request set.
  let thumb=sharp(bytes).rotate();
  if(item.crop){const [left,top,width,height]=item.crop;thumb=thumb.extract({left,top,width,height});}
  else if(metadata.width>200&&metadata.height>200){thumb=thumb.trim({threshold:12});}
  const trimmed=await thumb.png().toBuffer();
  const smallMetadata=await sharp(trimmed).metadata();
  const natural=Math.max(smallMetadata.width,smallMetadata.height);
  for(const size of [112,224]){
   const content=Math.min(size,natural);
   const file='assets/product-media/'+identity+'-'+size+'.webp';
   await sharp(trimmed).resize(content,content,{fit:'contain',background:'#ffffff',withoutEnlargement:true})
    .extend({top:Math.floor((size-content)/2),bottom:Math.ceil((size-content)/2),left:Math.floor((size-content)/2),right:Math.ceil((size-content)/2),background:'#ffffff'})
    .webp({quality:82,effort:5}).toFile(path.join(root,file));files.push(file);
  }
  const full='assets/product-media/'+identity+'-full.webp';
  await sharp(bytes).rotate().resize({width:960,height:960,fit:'inside',withoutEnlargement:true}).webp({quality:86,effort:5}).toFile(path.join(root,full));files.push(full);
  const sizes=[112,224,'full'].map(size=>fs.statSync(path.join(root,'assets/product-media/'+identity+'-'+size+'.webp')).size);
  if(sizes[0]>14000||sizes[1]>30000)throw new Error('缩略图超过预算：'+target);
  encoded.set(identity,[identity,metadata.width,metadata.height]);
  report.push({source:item.source,id:identity,originalBytes:bytes.length,bytes:sizes});
 }
 catalog[target]=encoded.get(identity);
}
const live=new Set(files.map(file=>path.basename(file)));
for(const name of fs.readdirSync(output))if(/^[a-f0-9]{16}-(112|224|full)\.webp$/.test(name)&&!live.has(name))fs.unlinkSync(path.join(output,name));
const text='// Generated by dev/media/build-images.mjs. Source provenance: dev/media/*.json.\n'
 +'// [content hash, original width, original height]; only file paths, no embedded image bytes.\n'
 +'const productMediaAssets = '+JSON.stringify(catalog,null,1)+';\n';
fs.writeFileSync(path.join(root,'src/data/product-media.js'),text);
const manifestFile=path.join(root,'manifest.json'),manifest=JSON.parse(fs.readFileSync(manifestFile,'utf8'));
manifest.images=[...manifest.images.filter(file=>!file.startsWith('assets/product-media/')),...files.sort()];
fs.writeFileSync(manifestFile,JSON.stringify(manifest,null,2)+'\n');
const summary={families:encoded.size,replacedSpus:definitions.replacements.filter(item=>item.target.startsWith('assets/spu-images/')).length,unresolvedSpuRows:definitions.unresolved,remoteSources:remote.sources.length,generatedIllustrations:generated.sources.length,
 originalBytes:report.reduce((n,r)=>n+r.originalBytes,0),thumbnailBytes:report.reduce((n,r)=>n+r.bytes[0],0),retinaBytes:report.reduce((n,r)=>n+r.bytes[1],0),fullBytes:report.reduce((n,r)=>n+r.bytes[2],0),sources:report};
fs.writeFileSync(path.join(root,'outputs/image-quality-assets.json'),JSON.stringify(summary,null,2));
console.log(JSON.stringify({...summary,sources:undefined}));
