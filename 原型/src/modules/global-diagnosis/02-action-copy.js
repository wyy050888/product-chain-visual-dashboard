function gdRefreshActionCopy(task){
 const text=value=>gdLegacyActionCopy.get(value)||value;
 const roles=task.responsibilities?.map(role=>{
  const action=text(role.action),completionCriteria=text(role.completionCriteria);
  return action===role.action&&completionCriteria===role.completionCriteria?role:{...role,action,completionCriteria};
 });
 const oldPlan=task.responsibilities?.map(role=>role.assignee+'：'+role.action).join('\n');
 const plan=roles&&task.plan===oldPlan?roles.map(role=>role.assignee+'：'+role.action).join('\n'):text(task.plan);
 const impact=typeof task.gdImpact==='string'?task.gdImpact.replace(/^准入储备 (\d+)，要求 (\d+)$/,'已准入供应商 $1 家，要求至少 $2 家'):task.gdImpact;
 const patch={plan,description:text(task.description),gdProblem:text(task.gdProblem),gdImpact:impact,completionCriteria:text(task.completionCriteria)};
 if(roles)patch.responsibilities=roles.some((role,i)=>role!==task.responsibilities[i])?roles:task.responsibilities;
 return Object.entries(patch).some(([key,value])=>value!==task[key])?{...task,...patch}:task;
}

