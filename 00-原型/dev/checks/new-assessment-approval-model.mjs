import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {verifyRollingModel} from './new-success-rolling.mjs';
export function verifyAssessmentApprovalModel(){
 const {ctx,products:{rolled,b,future},period,annualAt,quarterAt}=verifyRollingModel(),storage=new Map();
 ctx.localStorage={getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,value)};
 const q3=period(2026,3),q4=quarterAt(2026,4,'2026-10-24'),year=annualAt(2026,'2026-10-24');
 const baseline=ctx.nspSuccessFact(rolled,q3),annualBefore=ctx.nspSuccessFact(rolled,year);
 assert(!baseline.success&&!annualBefore.success&&ctx.nspSuccessFact(rolled,q4).included);
 assert.throws(()=>ctx.nspSaveApproval(rolled,q3,''),/特批原因/);
 assert.throws(()=>ctx.nspSaveApproval(b,period(2026,2),'无需特批'),/已达到/);
 assert.throws(()=>ctx.nspSaveApproval(future,period(2026,3),'未来产品'),/未纳入/);
 assert.throws(()=>ctx.nspSaveApproval(rolled,{...q3,key:'2026-Q4'},'错期'),/期间/);
 ctx.nspSaveApproval(rolled,year,'年度独立特批');
 assert(ctx.nspSuccessFact(rolled,year).success&&!ctx.nspSuccessFact(rolled,q3).success,'年度特批不自动变成季度成功');
 assert(ctx.nspSuccessFact(rolled,q4).included,'年度特批不退出季度考核');
 const approval=ctx.nspSaveApproval(rolled,q3,'季度特批原因');
 assert.equal(approval.effectiveDate,'2026-09-30');
 const approved=ctx.nspSuccessFact(rolled,q3);assert(approved.success&&approved.approval);assert.deepEqual(approved.facts,baseline.facts,'不改经营实际值');
 assert(!ctx.nspSuccessFact(rolled,{...q3,end:'2026-09-29'}).success,'截止日早于特批生效日不提前成功');
 assert(!ctx.nspSuccessFact(rolled,q4).included);assert(!ctx.nspSuccessFact(rolled,quarterAt(2027,1,'2027-01-15')).included,'特批成功跨年后不滚回');
 const rows=[rolled,rolled].map(p=>({...p,successAssessment:ctx.nspSuccessFact(p,q3)}));assert.equal(ctx.nspSuccessSummary(rows,q3).success,1,'同SPU特批成功只计一次');
 assert.throws(()=>ctx.nspSaveApproval(rolled,q3,'重复提交'),/已特批/);
 const snapshot=ctx.nspApprovalAudit(),restore=ctx.localStorage.setItem;
 const key=[...storage.keys()][0],saved=storage.get(key),changed=JSON.parse(saved);changed.history.push({action:'other-window'});storage.set(key,JSON.stringify(changed));
 assert.throws(()=>ctx.nspSaveApproval(rolled,q3,'',true),/已更新/,'旧窗口不能覆盖新记录');storage.set(key,saved);
 ctx.localStorage.setItem=()=>{throw Error('模拟存储失败')};
 assert.throws(()=>ctx.nspSaveApproval(rolled,q3,'',true),/保存失败/);assert.deepEqual(ctx.nspApprovalAudit(),snapshot,'存储失败不修改结果或日志');
 ctx.localStorage.setItem=restore;
 const reloaded=vm.createContext({localStorage:ctx.localStorage,DATA_CUTOFF:ctx.DATA_CUTOFF});
 vm.runInContext(fs.readFileSync(new URL('../../src/modules/new-products/00-success-approvals.js',import.meta.url),'utf8'),reloaded);
 assert.deepEqual(JSON.parse(JSON.stringify(reloaded.nspApprovalAudit())),JSON.parse(JSON.stringify(snapshot)),'刷新保留特批与操作记录');
 reloaded.DATA_CUTOFF='2026-09-01';assert.equal(reloaded.nspApprovalRead().records.length,2,'回看不能删除较晚生效的记录');assert.equal(reloaded.nspApprovalFor(rolled.spuId,q3.key),null,'较晚记录不提前生效');
 ctx.nspSaveApproval(rolled,year,'',true);assert(!ctx.nspSuccessFact(rolled,year).success&&ctx.nspSuccessFact(rolled,q3).success,'撤销年度不撤销季度');
 ctx.nspSaveApproval(rolled,q3,'',true);assert(!ctx.nspSuccessFact(rolled,q3).success&&ctx.nspSuccessFact(rolled,q4).included,'撤销季度恢复后续纳入');
 assert.deepEqual(ctx.nspSuccessFact(rolled,year).facts,annualBefore.facts);
 const q1=period(2026,1);ctx.nspSaveApproval(rolled,q1,'先特批后实际达标');
 rolled.days.push({date:'2026-02-10',gsvCents:110000000,profitCents:22000000,sales:100,returned:10});ctx.upRuleRevision++;
 ctx.nspSaveApproval(rolled,q1,'',true);assert(ctx.nspSuccessFact(rolled,q1).success,'撤销特批不能撤销自然达标');
 console.log('通过：特批季度/年度独立、滚出及撤销恢复、历史截止日、实际值不变、去重与持久化失败回滚');
}
