import {compassShopConfig} from './shop-admin.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
export async function shopConfig(page){
 const raw=[{shopId:'123',channel:'抖音',shopCategory:'旗舰店',assessed:false},{shopId:'123',channel:'天猫',shopCategory:'其他',assessed:true}];
 const ctx=vm.createContext({window:{},localStorage:{getItem:()=>null,setItem:()=>{}},sampleShopRows:()=>raw});
 vm.runInContext(fs.readFileSync(new URL('../../src/data/filter-catalog.js',import.meta.url),'utf8'),ctx);
 vm.runInContext(fs.readFileSync(new URL('../../src/data/shop-classification.js',import.meta.url),'utf8'),ctx);
 vm.runInContext(fs.readFileSync(new URL('../../src/modules/shop-config/01-model.js',import.meta.url),'utf8'),ctx);
 assert.equal(ctx.shcSetShop('抖音|123',{shopCategory:'专卖店',assessed:true}).ok,true);
 assert.equal(ctx.shcApplyConfig(raw[0]).shopCategory,'专卖店');assert.equal(ctx.shcApplyConfig(raw[1]).shopCategory,'无分类','同ID跨平台配置独立');
 assert.equal(ctx.shcSetShop('抖音|123',{shopCategory:'未知'}).ok,false);assert.equal(ctx.shcSetShop('抖音|123',{assessed:'yes'}).ok,false);
 assert.equal(ctx.shcSetShop('京东|不存在',{assessed:true}).ok,false);
 const rules=ctx.window.ShopClassification;
 for(const platform of ['抖音','快手','视频号','天猫','拼多多'])assert.deepEqual([...rules.allowed(platform)],['旗舰店','专卖店']);
 assert.deepEqual([...rules.allowed('京东')],['自营','POP旗舰店','POP专卖店']);
 for(const [old,current] of [['自营店','自营'],['旗舰店','POP旗舰店'],['专卖店','POP专卖店'],['C店','无分类'],['其他','无分类']])assert.equal(rules.normalize('京东',old),current);
 assert.equal(rules.resolve('抖音',{name:'名称旗舰店',shopCategory:'旗舰店',assessed:true},{shopCategory:'专卖店',assessed:false}).shopCategory,'专卖店','配置优先于名称');
 assert.equal(rules.resolve('抖音',{name:'名称旗舰店',assessed:true},{shopCategory:'C店',assessed:false}).shopCategory,'无分类','旧无效配置不能按名称强制归类');
 assert.equal(rules.infer('京东','京东自营旗舰店'),'自营');
 assert.equal(rules.infer('视频号','视频号店'),'无分类');
 assert.equal(ctx.shcSetShop('抖音|123',{shopCategory:'POP旗舰店'}).ok,false);
 assert.equal(ctx.shcSetShop('抖音|123',{shopCategory:'C店'}).ok,false);
 assert.equal(rules.resolve('抖音',{name:'名称旗舰店',assessed:true},{shopCategory:'待确认',assessed:false}).shopCategory,'无分类','旧待确认值兼容为无分类');
 const migrated=rules.store({version:1,shops:{'京东|1':{shopCategory:'自营店',assessed:false},'抖音|2':{shopCategory:'C店',assessed:true},'天猫|3':{assessed:false}}});
 assert.equal(migrated.shops['京东|1'].shopCategory,'自营');assert.equal(migrated.shops['抖音|2'].legacyShopCategory,'C店');assert.equal(migrated.shops['抖音|2'].assessed,true);assert.equal(migrated.shops['天猫|3'].assessed,false);
 assert.deepEqual(JSON.parse(JSON.stringify(rules.store(migrated))),JSON.parse(JSON.stringify(migrated)),'迁移幂等');
 await compassShopConfig(page);
}
