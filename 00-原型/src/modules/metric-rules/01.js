function metricLabelText(element) {
  return [...element.childNodes].filter(node => !(node.nodeType === 1 && node.classList.contains('metric-help')))
    .map(node => node.textContent).join('').trim();
}
function isReturnMetricLabel(label){
 return /^(?:(?:本期|上期|当前|累计|近\d+天))?(?:总退|已收退)(?:货率|率)?(?:目标|环比(?:增长(?:率)?)?|件数|超目标幅度)?$/.test(String(label).replace(/\s+/g,''));
}
function isReturnMetricHelpSuppressed(label,element){
 return isReturnMetricLabel(label)&&!element?.closest('#riskrail .riskcard[data-rp-board],.rp-list-table');
}
// 普通利润率不展示问号，净利润率保留原说明。
function isProfitMetricHelpSuppressed(label){
 const text=String(label).replace(/\s+/g,'');
 return text.length<=40&&/利润率/.test(text)&&!/净(?:利润|利)率/.test(text);
}
function metricDefinition(label, element) {
  label=String(label).replaceAll('上市','上线'); // 展示新词兼容原口径字典。
  if(isProfitMetricHelpSuppressed(label)||element&&isReturnMetricHelpSuppressed(label,element))return '';
  if (element?.closest('.qf-rank-row,.qf-list-table,.qf-detail-metrics,.qrb-business')) {
    const monthly = {
      平台罚款: '所选周期平台罚款金额；大于0触发预警。',
      资金冻结: '所选周期平台资金冻结事件金额；大于0触发预警。',
      链接下架: '所选周期被下架的商品链接数量；大于0触发预警。',
      退货率: '所选周期退货件数÷所选周期销售数×100%；'+brcResultText('quality-return')+'触发预警，上期缺失不判定。',
      进线率: '所选周期产品问题进线数÷所选周期销售数×100%；与上期等长区间相比，总进线率环比增长率'+brcDescribe('quality.contactDelta')+'触发预警；上期进线率为0或任一期缺失时不判定。'
    };
    if (monthly[label]) return monthly[label];
  }
  const compact = label.replace(/\s+/g, '').replace(/[（(](?:万元|元|件|项|个|%|百分比)[）)]/g, '');
  if(compact==='关键产品管控'&&element?.closest('#matrix.kpm-main'))return kpmGradeHelpText();
  const normalized = compact.replace(/^(?:本季度|本年度|季度|年度|月度|累计|季|月|年)(?=目标|销售额|规模达成率|完成率|数据差额|实际完成|累计完成|交付及时率|降本实际达成|累计降本实际达成)/, '');
  const definition = metricDefinitions[compact] || metricDefinitions[normalized];
  return typeof definition === 'function' ? definition() : definition || '';
}
function cleanMetricRule(text) {
  return text.replace(/演示阈值：/g, '阈值：').replace(/演示目标/g, '目标').replace(/当前演示/g, '当前')
    .replace(/单品演示口径：/g, '').replace(/演示[:：]?/g, '').replace(/模拟/g, '').trim();
}

