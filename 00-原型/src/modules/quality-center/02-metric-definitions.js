function qcMetricDemo(label,unit,personIndex,metricIndex){
 const sample=(personIndex+1)*13+(metricIndex+1)*7;
 if(unit==='%')return fmt(label.includes('复发率')?sample%9:78+sample%23,0)+'%';
 if(unit==='元')return fmt((sample%20+1)*1200)+' 元';
 if(label.includes('今日'))return String(sample%4);
 if(label.includes('本月'))return String(5+sample%12);
 if(label==='审核目标数')return String(14+sample%9);
 if(label==='已审数')return String(11+(sample-7)%9);
 if(label==='未审数')return '3';
 if(label==='质量管控数')return String(18+sample%8);
 if(label==='已管控数')return String(16+(sample-7)%8);
 if(label==='未管控数')return '2';
 if(label==='计划测试数量')return String(12+sample%9);
 if(label==='完成数量')return String(10+(sample-7)%9);
 return String(sample%12);
}
